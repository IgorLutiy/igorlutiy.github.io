function normalizeWord(word) {
  return String(word).toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/’/g, '')
    .replace(/ʼ/g, '')
    .trim();
}

function getWords(langCode, length) {
  const lang = languages[langCode];
  if (!lang || !lang.words[length]) return [];
  // уникальные + точная длина
  const seen = new Set();
  return lang.words[length]
    .map(normalizeWord)
    .filter(w => {
      if (w.length !== length || seen.has(w)) return false;
      seen.add(w);
      return true;
    });
}

function getAvailableLanguages() {
  return Object.keys(languages).map(code => ({
    code,
    name: languages[code].name,
    flag: languages[code].flag || ''
  }));
}
